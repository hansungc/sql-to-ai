콘서트: 8/10 예정, 온라인 관심도 정체

[분석 목표]
위 결과를 경영진 1페이지 보고서로 정리해 줘.

[결과 형식]
1. 핵심 메시지(1줄, 결론과 방향)
2. 주요 발견(3개, 각각 "현황-의미" 형식, 2줄 이내)
3. 제안(2개, 구체적인 액션과 시기 포함)
기술 용어 없이 비즈니스 용어로.
*/

