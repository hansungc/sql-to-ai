-- ============================================================
-- 예제 1 · [20.1] 구조 지정 기법 - 항목과 순서 명시
-- ============================================================

-- ▼ 프롬프트 (/* */ 안을 그대로 복사해 AI에 입력)
/*
[이전 결과]
Phoenix: 623,000회(업계 평균 850,000의 73%)
Celestial: 892,500회(업계 평균의 105%)
StarLight: 756,000회(업계 평균의 89%)

[분석 목표]
위 결과를 경영진 보고용으로 변환해 줘.

[결과 형식]
아티스트별로 다음 세 가지를 정리:
1. 현황: 핵심 숫자 한 줄
2. 의미: 좋은지 나쁜지 판단
3. 제안: 구체적인 액션 아이템 1개
*/

-- ============================================================
-- 예제 2 · [20.1] 예시 제공 기법 - One-Shot 예시 제시
