(아티스트별 스트리밍, 업계 비교, 해외 팬 비중 데이터)

[분석 목표]
팀장님께 슬랙으로 보낼 요약을 만들어 줘.

[결과 형식]
- 3줄 이내
- 표 없이 텍스트만
- SQL 용어 쓰지 마.
- 핵심 숫자와 제안만 포함
*/

