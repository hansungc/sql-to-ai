Celestial: 892,500회(업계 평균의 105%), 신곡 효과

[분석 목표]
다음 예시와 같은 형식으로 나머지 아티스트도 정리해 줘.

[결과 형식 예시]
Phoenix | 업계 73% · 콘서트 8/10 임박 | 스트리밍 인증 이벤트 시급

[결과 형식]
위 형식(아티스트 | 현황 요약 | 제안)으로 Celestial, StarLight도 정리해 줘.
*/

