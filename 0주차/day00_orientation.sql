-- ============================================================
-- 예제 9 · [DML - 데이터 삭제]
-- ============================================================

-- ▶ 실행해 보세요 — 이 아티스트를 참조하는 행이 있어 "Cannot delete or update a parent row" 에러가 납니다
DELETE FROM artists
WHERE artist_id=1;

-- ============================================================
-- 예제 10 · [DCL - 권한 부여]
-- ============================================================

-- ▶ 실행해 보세요 — user1 계정이 없어 "You are not allowed to create a user" 에러가 납니다
--   권한을 주려면 계정이 먼저 있어야 합니다(5주차 환경셋업의 계정 생성 SQL 참고)
GRANT SELECT ON artists TO 'user1';

-- ============================================================
-- 예제 11 · [DCL - 권한 회수]
-- ============================================================

-- ▶ 실행해 보세요 — 부여한 적 없는 권한이라 "There is no such grant defined" 에러가 납니다
REVOKE SELECT ON artists FROM 'user1';

-- ============================================================
-- 예제 12 · [TCL - 트랜잭션 시작]
-- ============================================================

-- ▶ 실행해 보세요 — 성공하지만 화면에는 아무것도 나오지 않습니다.
--   트랜잭션이 열렸을 뿐이며, 예제 15·16과 이어서 보세요
START TRANSACTION;

-- ============================================================
-- 예제 13 · [TCL - 트랜잭션 계좌이체 예시 (출금)]
-- ============================================================

-- ▶ 실행해 보세요 — accounts는 개념 설명용 가상 테이블이라 "doesn't exist" 에러가 납니다
UPDATE accounts SET balance=balance-10000 WHERE account_id='A';

-- ============================================================
-- 예제 14 · [TCL - 트랜잭션 계좌이체 예시 (입금)]
-- ============================================================

-- ▶ 실행해 보세요 — 예제 13과 마찬가지로 "doesn't exist" 에러가 납니다
UPDATE accounts SET balance=balance+10000 WHERE account_id='B';

-- ============================================================
-- 예제 15 · [TCL - COMMIT]
-- ============================================================

-- ▶ 실행해 보세요 — 예제 12에서 연 트랜잭션을 확정합니다. 화면 출력은 없습니다
COMMIT;

-- ============================================================
-- 예제 16 · [TCL - ROLLBACK]
-- ============================================================

-- ▶ 실행해 보세요 — 되돌릴 변경이 없어 아무 일도 일어나지 않습니다. 화면 출력도 없습니다
ROLLBACK;

-- ============================================================
-- 예제 17 · [첫 쿼리 실행]
-- ============================================================

-- ▶ 실행해 보세요 — db-fiddle 첫 화면의 예시입니다. test 테이블이 없어 에러가 납니다
SELECT * FROM test;

