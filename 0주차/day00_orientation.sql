-- 무엇을 판단하는지는 교재 본문에 있습니다. 예제 제목의 절 번호가 교재의 절 번호와
-- 같으니, 막히는 곳이 있으면 해당 절을 펼쳐 보세요.
--
-- 이 파일은 개념을 훑는 자리라 '에러가 나는 것이 정상'인 예제가 많습니다.
-- 에러 메시지를 읽는 것도 연습이니, ▶ 표시가 붙은 것은 직접 실행해 보세요.
--
-- 읽는 법
--   -- ======  구분선     이 줄부터 새 예제입니다
--   주석 없는 SQL           그대로 실행하면 됩니다
--   ▶ 실행해 보세요        실행해도 됩니다. 무엇을 보게 될지 같은 줄에 적어 두었습니다
--   ✕ 실행하지 마세요       데이터가 실제로 바뀝니다. 사유는 같은 줄에 적어 두었습니다
-- ============================================

-- ============================================================
-- 예제 1 · [SQL 기본 예시 - 비전공자 설명]
-- ============================================================

SELECT artist_name
FROM artists
WHERE artist_type='SOLO';

-- ============================================================
-- 예제 2 · [DDL - 테이블 생성]
-- ============================================================

-- ▶ 실행해 보세요 — artists가 이미 있어 "Table 'artists' already exists" 에러가 납니다
CREATE TABLE artists(
  artist_id INT,
  artist_name VARCHAR(100),
  artist_type VARCHAR(20)
);

-- ============================================================
-- 예제 3 · [DDL - 열 추가]
-- ============================================================

-- ▶ 실행해 보세요 — debut_date가 이미 있어 "Duplicate column name" 에러가 납니다
ALTER TABLE artists ADD debut_date DATE;

-- ============================================================
-- 예제 4 · [DDL - 열 삭제]
-- ============================================================

-- ✕ 실행하지 마세요 — 에러 없이 성공해서 debut_date 칼럼이 실제로 사라집니다.
--   1주차 이후 예제가 이 칼럼을 쓰므로, 실행했다면 harmony_v1.sql을 다시 적재하세요
-- ALTER TABLE artists DROP COLUMN debut_date;

-- ============================================================
-- 예제 5 · [DDL - 테이블 삭제]
-- ============================================================

-- ▶ 실행해 보세요 — 다른 테이블이 외래 키로 참조 중이라 "Cannot drop table" 에러가 납니다
DROP TABLE artists;

-- ============================================================
-- 예제 6 · [DML - 데이터 조회]
-- ============================================================

SELECT * FROM artists;

-- ============================================================
-- 예제 7 · [DML - 데이터 추가]
-- ============================================================

-- ▶ 실행해 보세요 — artist_id 1이 이미 있어 "Duplicate entry '1'" 에러가 납니다
INSERT INTO artists(artist_id, artist_name, artist_type)
VALUES(1, 'StarLight', 'GROUP');

-- ============================================================
-- 예제 8 · [DML - 데이터 수정]
-- ============================================================

-- ✕ 실행하지 마세요 — 에러 없이 성공해서 artist_id 1의 artist_type이 실제로 바뀝니다.
--   실행했다면 harmony_v1.sql을 다시 적재하세요
-- UPDATE artists
-- SET artist_type='SOLO'
