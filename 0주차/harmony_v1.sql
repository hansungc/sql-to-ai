-- PART 1: 테이블 생성 (DDL)
-- ============================================

-- 아티스트 테이블: 그룹 및 솔로 아티스트 정보
CREATE TABLE artists (
    artist_id INT PRIMARY KEY COMMENT '아티스트ID',
    artist_name VARCHAR(100) NOT NULL COMMENT '아티스트명',
    artist_type VARCHAR(20) NOT NULL COMMENT '아티스트유형(GROUP/SOLO)',
    debut_date DATE COMMENT '데뷔일',
    member_count INT COMMENT '멤버수',
    agency VARCHAR(100) COMMENT '소속사',
    genre VARCHAR(50) COMMENT '장르'
) COMMENT '아티스트 마스터 - 그룹 및 솔로 아티스트의 기본 정보';

-- 멤버 테이블: 그룹 아티스트의 멤버 정보
CREATE TABLE members (
    member_id INT PRIMARY KEY COMMENT '멤버ID',
    member_name VARCHAR(100) NOT NULL COMMENT '멤버명',
    artist_id INT COMMENT '아티스트ID',
    birth_date DATE COMMENT '생년월일',
    position VARCHAR(50) COMMENT '포지션(메인보컬/리더 등)',
    nationality VARCHAR(50) COMMENT '국적',
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT '그룹 멤버 정보 - 각 그룹 아티스트의 멤버 상세';

-- 앨범 테이블: 발매된 앨범 정보
CREATE TABLE albums (
    album_id INT PRIMARY KEY COMMENT '앨범ID',
    album_name VARCHAR(200) NOT NULL COMMENT '앨범명',
    artist_id INT COMMENT '아티스트ID',
    release_date DATE COMMENT '발매일',
    album_type VARCHAR(50) COMMENT '앨범유형(정규/미니/싱글)',
    total_tracks INT COMMENT '총트랙수',
    price INT COMMENT '가격',
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT '앨범 정보 - 발매된 앨범의 기본 정보 및 가격';

-- 트랙 테이블: 앨범 내 수록곡 정보
CREATE TABLE tracks (
    track_id INT PRIMARY KEY COMMENT '트랙ID',
    track_name VARCHAR(200) NOT NULL COMMENT '트랙명',
    album_id INT COMMENT '앨범ID',
    track_number INT COMMENT '트랙번호',
    duration INT COMMENT '재생시간(초)',
    genre VARCHAR(50) COMMENT '장르',
    FOREIGN KEY (album_id) REFERENCES albums(album_id)
) COMMENT '트랙(곡) 정보 - 각 앨범에 수록된 곡들의 상세 정보';

-- 상품 테이블: 판매 중인 굿즈 및 상품 정보
CREATE TABLE products (
    product_id INT PRIMARY KEY COMMENT '상품ID',
    product_name VARCHAR(200) NOT NULL COMMENT '상품명',
    artist_id INT COMMENT '아티스트ID',
    category VARCHAR(50) COMMENT '카테고리(응원봉/포토카드/의류 등)',
    price INT COMMENT '가격',
    stock_quantity INT COMMENT '재고수량',
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT '상품(굿즈) 정보 - 판매 중인 아티스트 관련 상품';

-- 공연 테이블: 콘서트 및 쇼케이스 정보
CREATE TABLE concerts (
    concert_id INT PRIMARY KEY COMMENT '공연ID',
    concert_name VARCHAR(200) NOT NULL COMMENT '공연명',
    artist_id INT COMMENT '아티스트ID',
    venue VARCHAR(200) COMMENT '공연장',
    concert_date DATE COMMENT '공연일',
    ticket_price INT COMMENT '티켓가격',
    total_seats INT COMMENT '총좌석수',
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT '공연 정보 - 콘서트, 팬미팅 등 공연 이벤트';

-- 팬 테이블: 플랫폼 회원(팬) 정보
CREATE TABLE fans (
    fan_id INT PRIMARY KEY COMMENT '팬ID',
    fan_name VARCHAR(100) NOT NULL COMMENT '팬이름',
    email VARCHAR(200) COMMENT '이메일',
    join_date DATE COMMENT '가입일',
    membership_level VARCHAR(50) COMMENT '멤버십등급(VIP/프리미엄/일반)',
    favorite_artist_id INT COMMENT '최애아티스트ID',
    country VARCHAR(50) COMMENT '국가',
    FOREIGN KEY (favorite_artist_id) REFERENCES artists(artist_id)
) COMMENT '팬 정보 - 플랫폼 회원의 기본 정보 및 최애 아티스트';

-- 주문 테이블: 상품 구매 내역
CREATE TABLE orders (
    order_id INT PRIMARY KEY COMMENT '주문ID',
    fan_id INT COMMENT '팬ID',
    product_id INT COMMENT '상품ID',
    order_date DATE COMMENT '주문일',
    quantity INT COMMENT '수량',
    total_amount INT COMMENT '총주문금액(실제 결제액. 할인 등으로 수량x정가와 다를 수 있음)',
    FOREIGN KEY (fan_id) REFERENCES fans(fan_id),
    FOREIGN KEY (product_id) REFERENCES products(product_id)
) COMMENT '주문 내역 - 팬들의 상품 구매 이력';

-- 스트리밍 테이블: 음원 재생 로그 (7개 컬럼 - 교재와 일치)
CREATE TABLE streaming (
    stream_id INT PRIMARY KEY COMMENT '스트림ID',
    fan_id INT COMMENT '팬ID',
    track_id INT COMMENT '트랙ID',
    stream_date DATE COMMENT '재생일',
    stream_datetime DATETIME COMMENT '재생일시',
    play_count INT COMMENT '재생횟수',
    platform VARCHAR(50) COMMENT '플랫폼(Melon/Genie/Spotify 등)',
    FOREIGN KEY (fan_id) REFERENCES fans(fan_id),
    FOREIGN KEY (track_id) REFERENCES tracks(track_id)
) COMMENT '스트리밍 로그 - 음원 재생 이력 및 플랫폼 정보';

-- 팬활동 테이블: 팬들의 플랫폼 활동 로그
CREATE TABLE fan_activities (
    activity_id INT PRIMARY KEY COMMENT '활동ID',
    fan_id INT COMMENT '팬ID',
    activity_type VARCHAR(50) COMMENT '활동유형(login/stream/purchase/comment 등)',
    activity_datetime DATETIME COMMENT '활동일시',
    platform VARCHAR(50) COMMENT '플랫폼(Web/Instagram/Twitter 등)',
    artist_id INT COMMENT '아티스트ID',
    FOREIGN KEY (fan_id) REFERENCES fans(fan_id),
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT '팬 활동 로그 - 다양한 채널에서의 팬 활동 추적';

-- 일별차트 테이블: 음원 차트 순위 데이터
CREATE TABLE daily_charts (
    chart_id INT PRIMARY KEY COMMENT '차트ID',
    track_id INT COMMENT '트랙ID',
    chart_date DATE COMMENT '차트일',
    chart_rank INT COMMENT '차트순위',
    daily_streams INT COMMENT '일간재생수',
    rank_change INT COMMENT '순위변동',
    FOREIGN KEY (track_id) REFERENCES tracks(track_id)
) COMMENT '일별 차트 - 음원 차트 순위 및 스트리밍 수 추적';

-- 팬사인회 테이블: 팬사인회 이벤트 정보
CREATE TABLE fansign_events (
    event_id INT PRIMARY KEY COMMENT '이벤트ID',
    artist_id INT COMMENT '아티스트ID',
    event_date DATE COMMENT '이벤트일',
    min_album_purchase INT COMMENT '최소앨범구매수',
    total_participants INT COMMENT '총참가자수',
    total_cost INT COMMENT '총비용',
    total_revenue INT COMMENT '총수익',
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT '팬사인회 이벤트 - 팬사인회 개최 정보 및 비용/수익';

-- 팬사인회참가자 테이블: 팬사인회 참가 내역
CREATE TABLE fansign_participants (
    participant_id INT PRIMARY KEY COMMENT '참가자ID',
    event_id INT COMMENT '이벤트ID',
    fan_id INT COMMENT '팬ID',
    album_purchase_count INT COMMENT '앨범구매수',
    FOREIGN KEY (event_id) REFERENCES fansign_events(event_id),
    FOREIGN KEY (fan_id) REFERENCES fans(fan_id)
) COMMENT '팬사인회 참가자 - 각 팬사인회의 참가자 및 앨범 구매 수';

-- 포토카드거래 테이블: 포토카드 2차 거래 시장 데이터
CREATE TABLE photocard_trades (
    trade_id INT PRIMARY KEY COMMENT '거래ID',
    product_id INT COMMENT '상품ID',
    trade_date DATE COMMENT '거래일',
    trade_price INT COMMENT '거래가격',
    trade_count INT COMMENT '거래수량',
    seller_fan_id INT COMMENT '판매자팬ID',
    buyer_fan_id INT COMMENT '구매자팬ID',
    FOREIGN KEY (product_id) REFERENCES products(product_id),
    FOREIGN KEY (seller_fan_id) REFERENCES fans(fan_id),
    FOREIGN KEY (buyer_fan_id) REFERENCES fans(fan_id)
) COMMENT '포토카드 거래 - 2차 거래 시장의 거래 내역 및 가격';

-- 구독이력 테이블: 멤버십 구독 상태 추적
CREATE TABLE subscription_history (
    subscription_id INT PRIMARY KEY COMMENT '구독ID',
    fan_id INT COMMENT '팬ID',
    status VARCHAR(20) COMMENT '상태(active/churned/reactivated)',
    start_date DATE COMMENT '시작일',
    end_date DATE COMMENT '종료일',
    monthly_fee INT COMMENT '월구독료',
    FOREIGN KEY (fan_id) REFERENCES fans(fan_id)
) COMMENT '구독 이력 - 팬들의 멤버십 구독 상태 및 이력';

-- 업계벤치마크 테이블: 업계 평균 지표
CREATE TABLE industry_benchmarks (
    benchmark_id INT PRIMARY KEY COMMENT '벤치마크ID',
    metric_name VARCHAR(100) COMMENT '지표명',
    category VARCHAR(50) COMMENT '카테고리',
    benchmark_value DECIMAL(15,2) COMMENT '벤치마크값',
    measurement_date DATE COMMENT '측정일'
) COMMENT '업계 벤치마크 - 업계 평균 스트리밍, 판매량 등 비교 지표';

-- SNS반응 테이블: 소셜미디어 반응 데이터 (JSON)
CREATE TABLE sns_reactions (
    reaction_id INT PRIMARY KEY COMMENT '반응ID',
    artist_id INT COMMENT '아티스트ID',
    platform VARCHAR(50) COMMENT '플랫폼(Twitter/Instagram/TikTok 등)',
    posted_datetime DATETIME COMMENT '게시일시',
    reaction_data JSON COMMENT '반응데이터(좋아요/댓글/공유수 등 JSON)',
    FOREIGN KEY (artist_id) REFERENCES artists(artist_id)
) COMMENT 'SNS 반응 - 소셜미디어 플랫폼별 반응 데이터 (JSON 형식)';

