-- 읽는 법
--   -- ======  구분선     이 줄부터 새 예제입니다
--   주석 없는 SQL           그대로 실행하면 됩니다
--   ▶ 실행해 보세요       실행해도 됩니다. 무엇을 보게 될지 같은 줄에 적어 두었습니다
-- ============================================

-- ============================================================
-- 예제 1 · [1.1] SELECT의 기본 문법
-- ============================================================

-- ▶ 실행해 보세요 — 대괄호는 자리를 표시한 것이라 그대로 실행하면 문법 에러가 납니다
SELECT [칼럼명]
FROM [테이블명]
LIMIT [개수];

-- ============================================================
-- 예제 2 · [1.1] 기본 SELECT 예제
-- ============================================================

SELECT artist_name
FROM artists
LIMIT 3;

-- ============================================================
-- 예제 3 · [1.1] 전체 구조 파악하기 - SELECT *
-- ============================================================

SELECT *
FROM artists
LIMIT 3;

-- ============================================================
-- 예제 4 · [1.1] 필요한 칼럼만 선택하기
-- ============================================================

SELECT artist_name, artist_type, debut_date
FROM artists
LIMIT 3;

-- ============================================================
-- 예제 5 · [1.1] streaming 테이블 조회
-- ============================================================

SELECT *
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 6 · [1.1] fans 테이블 조회
-- ============================================================

SELECT fan_id, fan_name, membership_level, country
FROM fans
LIMIT 3;

-- ============================================================
-- 예제 7 · [1.1] 영문 칼럼명 예제
-- ============================================================

SELECT artist_name, artist_type, debut_date
FROM artists
LIMIT 1;

-- ============================================================
-- 예제 8 · [1.1] 재생 횟수 조회
-- ============================================================

SELECT fan_id, play_count
FROM streaming
LIMIT 1;

-- ============================================================
-- 예제 9 · [1.2] AS 기본 문법
-- ============================================================

-- ▶ 실행해 보세요 — 대괄호는 자리를 표시한 것이라 그대로 실행하면 문법 에러가 납니다
SELECT 칼럼명 AS `별칭`
FROM 테이블명;

-- ============================================================
-- 예제 10 · [1.2] 여러 칼럼에 한글 별칭 붙이기
-- ============================================================

SELECT
  artist_name AS `아티스트명`,
  artist_type AS `유형`,
  debut_date AS `데뷔일`
FROM artists
LIMIT 3;

-- ============================================================
-- 예제 11 · [1.2] 사칙연산으로 수익 계산하기
-- ============================================================

SELECT
  fan_id AS `팬 번호`,
  play_count AS `재생 횟수`,
  play_count * 7 AS `예상 수익`
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 12 · [1.2] 시간 변환 - 초를 분으로
-- ============================================================

SELECT
  track_name AS `곡명`,
  duration AS `길이_초`,
  duration DIV 60 AS `분`,
  duration % 60 AS `초`
FROM tracks
LIMIT 3;

-- ============================================================
-- 예제 13 · [1.2] SELECT에 고정 값 넣기
-- ============================================================

SELECT
  stream_id AS `스트리밍 번호`,
  track_id AS `곡 번호`,
  'Celestial' AS `아티스트`,
  'Universe' AS `곡명`,
  play_count AS `재생 횟수`
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 14 · [1.3] 신곡 스트리밍 데이터 확인
-- ============================================================

SELECT *
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 15 · [1.3] 필요한 칼럼만 선택하기
-- ============================================================

SELECT stream_id, platform, play_count, stream_datetime
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 16 · [1.3] 한글 별칭으로 가독성 높이기
-- ============================================================

SELECT
  stream_id AS `스트리밍 번호`,
  platform AS `플랫폼`,
  play_count AS `재생 횟수`,
  stream_datetime AS `첫 재생 시각`
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 17 · [1.3] 고정 값으로 맥락 추가하기
-- ============================================================

SELECT
  stream_id AS `스트리밍 번호`,
  'Celestial' AS `아티스트`,
  'Universe' AS `곡명`,
  platform AS `플랫폼`,
  play_count AS `재생 횟수`,
  stream_datetime AS `첫 재생 시각`
FROM streaming
LIMIT 3;

-- ============================================================
-- 예제 18 · [1.3] 예상 수익까지 계산하기
-- ============================================================

SELECT
  stream_id AS `스트리밍 번호`,
  'Celestial' AS `아티스트`,
  'Universe' AS `곡명`,
  platform AS `플랫폼`,
  play_count AS `재생 횟수`,
  play_count * 7 AS `예상 수익`
FROM streaming
LIMIT 3;
