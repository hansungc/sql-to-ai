-- ▼ 프롬프트 (/* */ 안을 그대로 복사해 AI에 입력)
/*
[스키마 정보]
테이블: [테이블명]([칼럼1], [칼럼2], ...)
- [칼럼] 가능한 값 '[값1]', '[값2]'

[요청]
위 [테이블]을 사용해서 SQL을 작성해 줘.: [조건]을 만족하는 [칼럼들] 조회
*/

-- ============================================================
-- 예제 2 · [L.1] 템플릿 1 실전 예시 - 한국 VIP 팬 이름 조회
-- ============================================================

-- ▼ 프롬프트 (/* */ 안을 그대로 복사해 AI에 입력)
/*
[스키마 정보]
테이블: fans(fan_id, fan_name, membership_level, country)
- membership_level: 가능한 값 'VIP', '프리미엄', '일반'
- country: 가능한 값 '대한민국', '일본', '미국'

[요청]
위 테이블을 사용해서 SQL을 작성해 줘.: 한국의 VIP 팬 이름 조회
*/

-- ▼ AI가 만든 SQL  ▶ 실행해서 결과를 비교하세요
SELECT fan_name
FROM fans
WHERE country='대한민국'
  AND membership_level='VIP';

