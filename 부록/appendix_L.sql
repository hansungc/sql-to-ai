/*
[스키마 정보]
테이블: [테이블명]([칼럼1], [칼럼2], ...)
- [그룹 칼럼]: 값 '[A]', '[B]', '[C]'
- [집계 칼럼]: [설명]

[요청]
위 테이블을 사용해서 SQL을 작성해 줘.: [그룹]별 [집계 함수]([대상]) 조회
*/

-- ============================================================
-- 예제 4 · [L.2] 템플릿 2 실전 예시 - 플랫폼별 총 재생 횟수
-- ============================================================

-- ▼ 프롬프트 (/* */ 안을 그대로 복사해 AI에 입력)
/*
[스키마 정보]
테이블: streaming(stream_id, platform, play_count, stream_date)
- platform: 값 'Melon', 'Genie', 'Spotify', 'Bugs'
- play_count: 재생 횟수(정수)

[요청]
위 테이블을 사용해서 SQL을 작성해 줘.: 플랫폼별 `총 재생 횟수`를 내림차순으로 조회
*/

-- ▼ AI가 만든 SQL  ▶ 실행해서 결과를 비교하세요
SELECT platform, SUM(play_count) AS `total_play_count`
FROM streaming
GROUP BY platform
ORDER BY `total_play_count` DESC;
