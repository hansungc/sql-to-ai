-- ============================================
-- 『SQL부터 AI까지 데이터 분석 With 클로드 코드』 실습 파일
-- 부록 A  집계 함수 첫걸음 - COUNT, SUM, AVG 함수
--
-- 이 파일은 교재의 '실습 재료'입니다. 쿼리를 왜 그렇게 쓰는지, 결과를 어떻게 읽고
-- 무엇을 판단하는지는 교재 본문에 있습니다. 예제 제목의 절 번호가 교재의 절 번호와
-- 같으니, 막히는 곳이 있으면 해당 절을 펼쳐 보세요.
--
-- 실행 전제: harmony_db에 harmony_v1.sql(HARMONY 데이터셋) 적재
--
-- 읽는 법
--   -- ======  구분선     이 줄부터 새 예제입니다
--   주석 없는 SQL           그대로 실행하면 됩니다
-- ============================================

-- ============================================================
-- 예제 1 · [1] 전체 행 개수 세기 (COUNT 함수)
-- ============================================================

SELECT COUNT(*) AS `총 스트리밍 건수`
FROM streaming;

-- ============================================================
-- 예제 2 · [1] COUNT(*) vs COUNT(칼럼명) 비교
-- ============================================================

SELECT
  COUNT(*) AS `전체`,
  COUNT(email) AS `이메일 등록 팬 수`
FROM fans;

-- ============================================================
-- 예제 3 · [2] 칼럼 값 전체 합산 (SUM 함수)
-- ============================================================

SELECT SUM(play_count) AS `총 재생 횟수`
FROM streaming;

-- ============================================================
-- 예제 4 · [2] 계산식과 함께 사용하기 (SUM)
-- ============================================================

SELECT SUM(play_count * 7) AS `총 예상 수익`
FROM streaming;

-- ============================================================
-- 예제 5 · [3] 전체 평균 구하기 (AVG 함수)
-- ============================================================

SELECT AVG(play_count) AS `평균 재생 횟수`
FROM streaming;

-- ============================================================
-- 예제 6 · [3] ROUND로 깔끔하게 정리하기
-- ============================================================

SELECT ROUND(AVG(play_count), 1) AS `평균 재생 횟수`
FROM streaming;

-- ============================================================
-- 예제 7 · [3] 여러 집계 함수 동시 사용
-- ============================================================

SELECT
  COUNT(*) AS `스트리밍 건수`,
  SUM(play_count) AS `총 재생 횟수`,
  ROUND(AVG(play_count), 1) AS `평균 재생 횟수`
FROM streaming;
