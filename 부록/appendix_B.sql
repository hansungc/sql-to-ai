-- ============================================================
-- 예제 1 · [B.1] 재생 횟수로 팬 등급 분류하기
-- ============================================================

SELECT
  stream_id,
  fan_id,
  play_count,
  CASE
    WHEN play_count >=20 THEN '열성 팬'
    WHEN play_count >=10 AND play_count <20 THEN '일반 팬'
    ELSE '신규 팬'
  END AS `팬 분류`
FROM streaming
WHERE track_id=93
LIMIT 3;

-- ============================================================
-- 예제 2 · [B.2] 국가별 배송비 계산하기
-- ============================================================

SELECT
  fan_id,
  fan_name,
  country,
  CASE
    WHEN country='대한민국' THEN 3000
    WHEN country IN('제주', '도서산간') THEN 6000
    WHEN country IN('일본', '중국', '대만') THEN 15000
    ELSE 25000
  END AS `배송비`
FROM fans
WHERE membership_level='VIP'
LIMIT 3;

-- ============================================================
-- 예제 3 · [B.3] 등급별 할인가 계산하기
-- ============================================================

SELECT
  fan_id,
  fan_name,
  membership_level,
  CASE
    WHEN membership_level='VIP' THEN 100000 * 0.8
    WHEN membership_level='프리미엄' THEN 100000 * 0.9
    ELSE 100000
  END AS `결제 금액`
FROM fans
WHERE fan_id IN(1, 2, 4)
LIMIT 3;

