-- ============================================================
-- 예제 1 · [부록 G] NULL 계산의 특성
-- ============================================================

SELECT
  5+NULL AS `더하기`,
  10 * NULL AS `곱하기`,
  NULL=NULL AS `비교`;

-- ============================================================
-- 예제 2 · [부록 G] COALESCE로 NULL을 기본값으로 바꾸기
-- ============================================================

SELECT
  fan_name AS `팬명`,
  membership_level AS `등급`,
  COALESCE(email, '미등록') AS `연락처`
FROM fans
WHERE fan_id IN(3, 4, 5, 10);

-- ============================================================
-- 예제 3 · [부록 G] 집계 함수와 NULL의 관계
-- ============================================================

SELECT
  membership_level AS `등급`,
  COUNT(*) AS `전체 팬 수`,
  COUNT(email) AS `이메일 등록 수`,
  COUNT(*) - COUNT(email) AS `미등록 수`
FROM fans
GROUP BY membership_level
ORDER BY `전체 팬 수` DESC
LIMIT 3;

-- ============================================================
-- 예제 4 · [부록 G] NULLIF 동작 확인
-- ============================================================

SELECT
  NULLIF(500, 0) AS `재고 500`,
  NULLIF(0, 0) AS `재고 0`,
  ROUND(100.0/NULLIF(500, 0), 2) AS `정상 계산`,
  ROUND(100.0/NULLIF(0, 0), 2) AS `안전 처리`;

-- ============================================================
-- 예제 5 · [부록 G] 0 나누기 방지
-- ============================================================

SELECT
  p.product_name AS `상품명`,
  p.stock_quantity AS `재고`,
  COUNT(o.order_id) AS `주문 건수`,
  ROUND(COUNT(o.order_id) * 1.0/NULLIF(p.stock_quantity, 0), 4) AS `회전율`
FROM products p
JOIN orders o ON p.product_id=o.product_id
GROUP BY p.product_id, p.product_name, p.stock_quantity
ORDER BY `주문 건수` DESC
LIMIT 3;
